    /** 线路等级 1-5：5 最密（同走廊/短途），1 最疏（边疆支线） */
    public static int routeLevel(String from, String to, int km) {
        if (REMOTE_CITIES.contains(from) || REMOTE_CITIES.contains(to)) return 1;
        if (km < 250) return 5;
        if (railCorridorIndex(from, to) >= 0) return km < 1600 ? 5 : 4;
        boolean a = MEGA_HUBS.contains(from), b = MEGA_HUBS.contains(to);
        if (a && b) return 4;
        if (a || b) return km < 1200 ? 3 : 2;
        return km < 600 ? 3 : 2;
    }

