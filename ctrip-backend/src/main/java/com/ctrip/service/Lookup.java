    /**
     * 铁路历时（分钟）：不是单纯「里程 ÷ 一个速度」——350 高速线与 250 区域线旅速差一截，
     * 同一条线上标杆车（少停站）与站站停还能差出半小时。
     *
     * @param tierRoll 0-1 随机值，决定停站档（标杆车少停 / 普通 / 站站停）
     */
    public static int trainMinutes(int dist, String type, String from, String to, double tierRoll) {
        // 停站档：标杆车少停（站距放大），站站停多停（站距压缩）
        double tier = tierRoll < 0.15 ? 1.9 : (tierRoll > 0.76 ? 0.62 : 1);
        boolean hsr = onHsrCorridor(from, to);
        if ("G".equals(type) || "D".equals(type)) {
            // 区间运行速度（不含停站）：350 级线 G 300 / D 215，250 级线 G 185 / D 172
            double cruise = "G".equals(type) ? (hsr ? 300 : 185) : (hsr ? 215 : 172);
            // 平均站间距：350 级线停站稀，250 级线站站停
            double gap = ("G".equals(type) ? (hsr ? 220 : 130) : (hsr ? 160 : 105)) * tier;
            double dwell = "G".equals(type) ? 2 : 2.5;
            int stops = Math.max(0, (int) Math.round(dist / gap) - 1);
            return (int) Math.round(dist / cruise * 60 + 10 + stops * dwell);
        }
        // 普速：直达/特快/快速/普快的「含停站旅速」，干线高、支线低
        double cruise = switch (type) {
            case "Z" -> hsr ? 112 : 92;
            case "T" -> hsr ? 100 : 84;
            case "K" -> hsr ? 88 : 74;
            default -> hsr ? 78 : 66;
        };
        return (int) Math.round(dist / cruise * 60 + 10);
    }

    /** 航班轮挡时间（分钟）：巡航 750km/h（3000 公里以上洲际线 850）+ 40 分钟起降滑行，与民航公布时刻一致 */
    public static int flightMinutes(int dist) {
        return (int) Math.round(dist / (dist > 3000 ? 850.0 : 750.0) * 60 + 40);
    }

