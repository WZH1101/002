    /** 城市列表（省会/热门 + 地级市，顺序与前端一致） */
    public static final List<String> CITIES;
    public static final Map<String, String> STATIONS = new HashMap<>();
    public static final Map<String, String> AIRPORTS = new HashMap<>();
    public static final Map<String, String> BUS_STATIONS = new HashMap<>();
    public static final Map<String, double[]> CITY_COORDS = new HashMap<>();

    static {
        STATIONS.putAll(BASE_STATIONS);
        AIRPORTS.putAll(BASE_AIRPORTS);
        BUS_STATIONS.putAll(BASE_BUS_STATIONS);
        CITY_COORDS.putAll(BASE_COORDS);
        List<String> all = new ArrayList<>(BASE_CITIES);
        for (String line : PREF_CITY_DATA.split("\n")) {
            String row = line.trim();
            if (row.isEmpty() || row.startsWith("#")) continue;
            String[] p = row.split("\\|");
            if (p.length < 3) continue;
            String city = p[0];
            CITY_COORDS.put(city, new double[]{Double.parseDouble(p[1]), Double.parseDouble(p[2])});
            if (p.length > 3 && !p[3].equals("-")) STATIONS.putIfAbsent(city, p[3]);
            if (p.length > 4 && !p[4].equals("-")) AIRPORTS.putIfAbsent(city, p[4]);
            all.add(city);
        }
        CITIES = List.copyOf(all);
    }

    /** 获取铁路里程（无预置时按真实经纬度球面距离 × 1.2 估算，与前端规则一致） */
    public static int distance(String from, String to) {
        Integer d = RAIL_DISTANCES.get(from + "-" + to);
        if (d != null) return d;
        double[] a = CITY_COORDS.get(from);
        double[] b = CITY_COORDS.get(to);
        // 无铁路里程表时用真实经纬度估算（球面距离 × 1.2 铁路系数）
        if (a != null && b != null) {
            double rad = Math.PI / 180;
            double dLat = (b[0] - a[0]) * rad;
            double dLon = (b[1] - a[1]) * rad;
            double h = Math.pow(Math.sin(dLat / 2), 2)
                    + Math.cos(a[0] * rad) * Math.cos(b[0] * rad) * Math.pow(Math.sin(dLon / 2), 2);
            return (int) Math.round(6371 * 2 * Math.asin(Math.sqrt(h)) * 1.2);
        }
        int fi = CITIES.indexOf(from);
        int ti = CITIES.indexOf(to);
        if (fi < 0 || ti < 0) return 800;
        return 300 + Math.abs(fi - ti) * 260;
    }

