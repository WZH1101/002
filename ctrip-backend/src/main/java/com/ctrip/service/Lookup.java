    /** 航班计划起飞：05:20-23:00，早高峰与下午晚高峰加密，5 分钟取整 */
    public static int flightDepMinute(Random rnd) {
        int[][] bands = {{380, 480, 24}, {480, 720, 30}, {720, 1020, 20}, {1020, 1260, 22}, {1260, 1380, 4}};
        int sum = 0;
        for (int[] b : bands) sum += b[2];
        int cut = rnd.nextInt(sum);
        for (int[] b : bands) {
            cut -= b[2];
            if (cut <= 0) return (int) Math.round((b[0] + rnd.nextDouble() * (b[1] - b[0])) / 5.0) * 5;
        }
        return 8 * 60;
    }

    /**
     * 机票淡旺季系数（与前端 seasonFactor 同源）：春节前后、暑运、国庆、五一、元旦上浮，
     * 3 月、9 月开学后、11 月前后下浮，周末再加一点，最终夹在 0.80-1.55。
     * 只作用于经济舱——公务舱/头等舱按全价舱位定价，不随季节浮动。
     */
    public static double seasonFactor(String date) {
        if (date == null || date.length() < 10) return 1.0;
        try {
            LocalDate d = LocalDate.parse(date.substring(0, 10));
            int md = d.getMonthValue() * 100 + d.getDayOfMonth();
            double f;
            if (md >= 115 && md <= 225) f = 1.38;          // 春运
            else if (md >= 926 && md <= 1008) f = 1.42;    // 国庆黄金周
            else if (md >= 428 && md <= 505) f = 1.28;     // 五一
            else if (md >= 621 && md <= 831) f = 1.30;     // 暑运
            else if (md >= 1219 || md <= 114) f = 1.16;    // 元旦 / 冰雪季
            else if (md >= 401 && md <= 406) f = 1.10;     // 清明
            else if (md >= 301 && md <= 331) f = 0.84;     // 3 月淡季
            else if (md >= 901 && md <= 925) f = 0.86;     // 9 月开学淡季
            else if (md >= 1010 && md <= 1218) f = 0.88;   // 11 月前后淡季
            else f = 0.95;
            int dow = d.getDayOfWeek().getValue(); // 1=周一 … 7=周日
            if (dow == 6 || dow == 7) f += 0.06;
            else if (dow == 5) f += 0.03;
            return Math.min(1.55, Math.max(0.80, f));
        } catch (RuntimeException e) {
            return 1.0;
        }
    }
