    /** 车型结构：短途以 G/D 为主，长途普速占比明显上升；边疆支线（青藏、南疆等）无高铁 */
    public static String pickTrainType(int dist, boolean onHsr, double roll, boolean remote) {
        double r = roll;
        if (remote) return r < 0.35 ? "Z" : (r < 0.65 ? "T" : (r < 0.9 ? "K" : "P"));
        // 350 主走廊外：1500km 以上多为普速干线，700-1500km 的 250 级区域线仍有大量 D/G
        if (!onHsr) r = Math.min(0.85, r + (dist > 1500 ? 0.25 : (dist > 700 ? 0.12 : 0)));
        if (dist < 400) return r < 0.62 ? "G" : (r < 0.84 ? "D" : (r < 0.90 ? "Z" : (r < 0.95 ? "T" : "K")));
        if (dist < 1000) return r < 0.46 ? "G" : (r < 0.68 ? "D" : (r < 0.80 ? "Z" : (r < 0.90 ? "T" : "K")));
        if (dist < 2000) return r < 0.36 ? "G" : (r < 0.52 ? "D" : (r < 0.68 ? "Z" : (r < 0.84 ? "T" : "K")));
        return r < 0.26 ? "G" : (r < 0.38 ? "D" : (r < 0.58 ? "Z" : (r < 0.78 ? "T" : (r < 0.96 ? "K" : "P"))));
    }

    /**
     * 发车时段：高铁 06:00-22:00 且早/晚高峰加密；普速全天分布，含夜间车。
     * 12306 的时刻不是均匀铺开的：整点/半点最多（G 车尤其明显），15/45 分次之，其余才落到 5 分钟一格；
     * 标杆车（停站少、跑得快）多安排在整点/半点发，与前端 pickDepMinute 同一套规则。
     */
    public static int trainDepMinute(String type, int dist, Random rnd, double tierRoll) {
        boolean hsr = "G".equals(type) || "D".equals(type);
        int[][] bands = hsr
                ? new int[][]{{360, 480, 30}, {480, 660, 24}, {660, 960, 18}, {960, 1140, 16}, {1140, 1320, 12}}
                : new int[][]{{0, 360, 10}, {360, 720, 30}, {720, 1080, 28}, {1080, 1440, 32}};
        if (!hsr && dist < 300) bands = new int[][]{{360, 720, 40}, {720, 1080, 40}, {1080, 1260, 20}};
        int sum = 0;
        for (int[] b : bands) sum += b[2];
        int cut = rnd.nextInt(sum);
        int lo = bands[0][0], hi = bands[0][1];
        for (int[] b : bands) {
            cut -= b[2];
            if (cut <= 0) {
                lo = b[0];
                hi = b[1];
                break;
            }
        }
        double raw = lo + rnd.nextDouble() * (hi - lo);
        double mark = rnd.nextDouble();
        boolean flagship = hsr && tierRoll < 0.15;
        int m;
        if (mark < (flagship ? 0.62 : 0.30)) m = (int) Math.round(raw / 30.0) * 30;
        else if (mark < (flagship ? 0.80 : 0.48)) m = (int) Math.round(raw / 15.0) * 15;
        else m = (int) Math.round(raw / 5.0) * 5;
        return Math.max(0, Math.min(1430, m));
    }

    /** 车次号段：同一走廊用同一号段（京沪 G1-G199、京广 G401-G599…），支线给 5xxx */
    public static String trainNumber(String type, int dist, int corridorIdx, Random rnd, Set<String> used) {
        int base, span;
        if ("G".equals(type)) {
            int[] bases = {1, 401, 901, 1901, 1301, 2801};
            if (corridorIdx >= 0 && corridorIdx < bases.length) {
                base = bases[corridorIdx];
                span = 199;
            } else {
                base = dist < 800 ? 5000 : 6200;
                span = 699;
            }
        } else if ("D".equals(type)) {
            base = dist < 500 ? 1000 : (dist < 1200 ? 3000 : 7000);
            span = 899;
        } else if ("Z".equals(type) || "T".equals(type)) {
            base = 1;
            span = 298;
        } else if ("P".equals(type)) {
            base = 6001;
            span = 990;
        } else {
            base = dist < 800 ? 100 : 1000;
            span = 899;
        }
        for (int i = 0; i < 40; i++) {
            int n = base + rnd.nextInt(span);
            String no = "P".equals(type) ? String.valueOf(n) : type + n;
            if (used == null) return no;
            if (!used.contains(no)) {
                used.add(no);
                return no;
            }
        }
        return "P".equals(type) ? String.valueOf(base) : type + base;
    }

    /** 航班密度：国内京沪 22-30 班、支线 2-4 班；短途被高铁挤占，国际航线收窄 */
    public static int flightCountFor(int level, int dist, Random rnd, boolean intl) {
        int[][] dom = {{2, 4}, {4, 8}, {8, 14}, {14, 22}, {22, 30}};
        int[][] itl = {{1, 2}, {1, 3}, {2, 5}, {4, 8}, {6, 12}};
        int idx = Math.max(0, Math.min(4, level - 1));
        int[] band = (intl ? itl : dom)[idx];
        int n = band[0] + rnd.nextInt(band[1] - band[0] + 1);
        if (!intl) {
            // 短途航线民航基本被高铁挤占：<300km 一天 1-2 班，300-500km 减半
            if (dist < 300) return 1 + rnd.nextInt(2);
            if (dist < 500) n = Math.max(1, (int) Math.round(n * 0.5));
        }
        if (dist > 4000) n = Math.max(1, (int) Math.round(n * 0.7));
        return n;
    }

