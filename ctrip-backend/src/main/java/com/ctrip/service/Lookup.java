    /**
     * 按车型挑到发站：G/D 走高铁场，Z/T/K/P 走普速场，首项为主站。
     * seed 相同（车次号+端点）结果稳定，同一车次刷新不会跳站。
     */
    public static String stationFor(String city, String type, String seed) {
        String[][] pools = CITY_STATIONS.get(city);
        if (pools == null) return station(city);
        boolean hsr = "G".equals(type) || "D".equals(type);
        String[] pool = hsr ? pools[0] : pools[1];
        if (pool.length == 0) pool = hsr ? pools[1] : pools[0];
        if (pool.length == 0) return station(city);
        if (pool.length == 1) return pool[0];
        java.util.Random rnd = new java.util.Random((seed + "|" + city).hashCode());
        // 主站占比略高：真实到发站也集中在主站，其余车次分散到辅站
        return rnd.nextDouble() < 0.55 ? pool[0] : pool[1 + rnd.nextInt(pool.length - 1)];
    }

